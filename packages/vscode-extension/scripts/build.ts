import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

await Promise.all([mkdir("dist", { recursive: true }), mkdir("artifacts", { recursive: true })]);
const packages = new Map<string, string>();
const metadataDirectory = await mkdtemp(join(tmpdir(), "vplc-extension-build-"));
try {
  // The CLI reports compiler failures normally. esbuild's JS metafile API can
  // throw before rejecting its Promise on errors, leaving a Bun build hanging.
  const executable = createRequire(import.meta.url).resolve("esbuild/bin/esbuild");
  for (const [name, entry] of [
    ["extension", "src/extension.ts"],
    ["server", "src/server/main.ts"],
  ] as const) {
    const metadataFile = join(metadataDirectory, `${name}.json`);
    const child = Bun.spawn(
      [
        process.execPath,
        executable,
        entry,
        "--bundle",
        "--platform=node",
        "--target=node20",
        "--format=cjs",
        // Bundle workspace source; dist may be absent or stale during development.
        "--conditions=bun",
        "--sourcemap",
        "--log-level=warning",
        `--outfile=dist/${name}.cjs`,
        `--metafile=${metadataFile}`,
        ...(name === "extension" ? ["--external:vscode"] : []),
      ],
      { stdout: "inherit", stderr: "inherit" },
    );
    if (await child.exited)
      throw new Error(`Failed to bundle ${name}. See the compiler error above.`);
    const metadata = JSON.parse(await readFile(metadataFile, "utf8"));
    for (const path of Object.keys(metadata.inputs)) {
      const matches = [...path.matchAll(/node_modules\/((?:@[^/]+\/)?[^/]+)/g)];
      const match = matches.at(-1);
      if (match) packages.set(match[1]!, resolve(path.slice(0, match.index! + match[0].length)));
    }
  }
} finally {
  await rm(metadataDirectory, { recursive: true, force: true });
}
const notices = await Promise.all(
  [...packages]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(async ([name, root]) => {
      const licenses = (await readdir(root)).filter((file) =>
        /^licen[sc]e(?:\.(?:txt|md))?$/i.test(file),
      );
      if (!licenses.length) {
        const metadata = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
        // precond omits LICENSE from its npm files list. Keep the license from
        // its exact upstream release in the build inputs rather than omitting it.
        if (name === "precond" && metadata.version === "0.2.3")
          return `## ${name}\n\n${await readFile("scripts/licenses/precond-0.2.3.txt", "utf8")}`;
        const readme = await readFile(join(root, "README.md"), "utf8").catch(() => "");
        const section = readme.match(
          /^#{1,3} License\s*\n([\s\S]*?)(?=^#{1,3} |$(?![\s\S]))/m,
        )?.[1];
        if (
          section?.includes("Permission is hereby granted") &&
          section.includes("THE SOFTWARE IS PROVIDED")
        )
          return `## ${name}\n\n${section.trim()}`;
        throw new Error(`Missing license for bundled package ${name}@${metadata.version}`);
      }
      return `## ${name}\n\n${(await Promise.all(licenses.map((file) => readFile(join(root, file), "utf8")))).join("\n\n")}`;
    }),
);
await writeFile(
  "THIRD_PARTY_NOTICES.md",
  `# Third-party notices\n\nLicenses for dependencies bundled in the extension. Generated by scripts/build.ts.\n\n${notices.join("\n\n")}\n`,
);
